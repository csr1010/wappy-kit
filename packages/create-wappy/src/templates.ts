/**
 * T9.3 generators (SPEC.md §4.1 output: `index.ts`, `.env.sample`, `.gitignore`, `README.md`,
 * `package.json`) — enum-driven choices (model/framework/memory/router) are rendered by picking
 * between pre-written, already-shipped code paths (a `switch` selecting a one-line adapter
 * constructor), never freshly invented per choice. This module is pure — no I/O, no model calls,
 * fully snapshot-testable (T9.8 builds on this).
 *
 * No tools/connector wiring lives here (removed — see docs/SPEC.md's decisions log): domain
 * connectors (Shopify and anything else) are out of scope for this open-source repo now; they live
 * in a separate connectors repo/npm scope, wired into an agent by hand
 * (`AgentDeps.tools`/`invokeTools`), not generated by this CLI. A "tools" step (M9) and, before it,
 * a "skills" step (M8/M9, removed M12) used to sit here.
 *
 * Raw conversation history (local LibSQL file) and the router (LLM) are fixed — the interview no
 * longer offers alternatives that aren't implemented, so there is nothing here that can fail at
 * generation time for lack of code. Retrieved knowledge/RAG (a separate concern) IS a real choice —
 * see the `memory` interview step and `KNOWLEDGE_ENV`/`COGNEE_ENV` below. `.env.sample` is the
 * single place every credential goes; the interview never asks for one.
 */

export interface GeneratedFile {
  path: string;
  content: string;
}

export interface EnvVarSpec {
  name: string;
  required: boolean;
  description: string;
  /** Section heading in `.env.sample`. */
  group: string;
}

/** Version strings for this project's own npm packages, resolved by the caller (e.g. read from
 * each package's own `package.json` at generation time) — kept out of this pure module, which never
 * touches the filesystem. */
export interface PartVersions {
  core: string;
  harness: string;
  whatsapp: string;
  /** Only actually depended on when the productivity-agent interview step is answered "yes" — see
   * `renderPackageJson`. Always resolved regardless, same as every other part, so there's one code
   * path for reading real installed versions, not a productivity-specific branch in `versions.ts`. */
  productivity: string;
  /** Same "only when productivity=yes" story as `productivity` above. */
  connectorGoogle: string;
  /** Only actually depended on when `memory.backend === "cognee"` — same "always resolved
   * regardless" story as `productivity`/`connectorGoogle` above. */
  connectorCognee: string;
  /** `@wappy_ai/create-agent`'s own version — needed as a generated project's OWN dependency (not just
   * a scaffolding tool) so `npm run dev`/`status`/`doctor` can resolve the `wappy` bin it provides. */
  createWappy: string;
}

