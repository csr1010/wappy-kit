function renderPackageJson(opts: RenderProjectOptions): string {
  const { answers, versions, projectName } = opts;
  const deps: Record<string, string> = {
    "@wappy_ai/core": versions.core,
    "@wappy_ai/harness": versions.harness,
    "@wappy_ai/whatsapp": versions.whatsapp,
    // Provides the `wappy` bin (dev/status/reset/doctor) that this project's own scripts invoke —
    // a real runtime dependency here, not just the one-time scaffolder.
    "@wappy_ai/create-agent": versions.createWappy,
    ai: "^7.0.0",
    dotenv: "^17.0.0",
  };
  const modelDep = THIRD_PARTY_VERSIONS[answers.model.provider];
  deps[modelDep.pkg] = modelDep.range;
  if (answers.memory.backend === "local") {
    // createKnowledge({ client }) takes a real @libsql/client Client, not a URL — index.ts builds
    // one directly, so it needs to be a direct dependency here, not just a transitive one.
    deps["@libsql/client"] = "0.18.0";
  } else {
    deps["@wappy_ai/connector-cognee"] = versions.connectorCognee;
  }
  if (answers.productivity.enabled) {
    deps["@wappy_ai/productivity"] = versions.productivity;
    deps["@wappy_ai/connector-google"] = versions.connectorGoogle;
  }
  const pkg = {
    name: projectName ?? "wappy-bot",
    version: "0.1.0",
    private: true,
    type: "module",
    // The `ai` package (Vercel AI SDK — createVercelModel's real dependency, pulled in by every
    // generated project) requires Node >=22, not the commonly-assumed >=20 — confirmed against its
    // own package.json, not guessed. Declared here so `npm install` actually warns on an
    // incompatible Node version instead of failing confusingly later at runtime.
    engines: { node: ">=22" },
    // No build step exists yet — index.ts is run directly via wappy dev's dynamic import (dev.ts),
    // never compiled to index.js. `start: "node index.js"` was a stale placeholder that fails
    // MODULE_NOT_FOUND on any real install (caught by hand-testing a real npm install through a
    // local registry, not by the unit tests, which never actually run `npm start`). `start` now
    // means the same thing `dev` does until a real production build step exists.
    scripts: { dev: "wappy dev", start: "wappy dev" },
    dependencies: Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b))),
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

