function renderIndexTs(opts: RenderProjectOptions): string {
  const { answers } = opts;
  const model = modelSetup(answers.model.provider);
  const productivity = answers.productivity.enabled;
  const memoryBackend = answers.memory.backend;

  const harnessImports = ["createAgent", "createVercelModel", "createLibsqlMemory", "createLibsqlSessionProfileStore", "createLlmRouter", "createKnowledge", "createKnowledgeRag"];
  const whatsappImports = ["createWhatsAppChannel"];

  const lines: string[] = [];
  lines.push('import "dotenv/config";');
  lines.push('import { createInMemoryTracer, systemClock } from "@wappy_ai/core";');
  lines.push(`import { ${[...harnessImports].sort().join(", ")} } from "@wappy_ai/harness";`);
  lines.push(`import { ${[...whatsappImports].sort().join(", ")} } from "@wappy_ai/whatsapp";`);
  if (memoryBackend === "local") {
    lines.push('import { createClient } from "@libsql/client";');
  } else {
    lines.push('import { createCogneeKnowledge } from "@wappy_ai/connector-cognee";');
  }
  if (productivity) {
    lines.push('import { createConnectUiServer, createGoogleAssistant } from "@wappy_ai/productivity";');
    lines.push('import { createCalendarSearchFn, createGmailSearchFn, createGoogleOAuthPlugin, createGoogleTokenStore } from "@wappy_ai/connector-google";');
  }
  lines.push(model.importLine);
  lines.push("");

  lines.push(`const model = createVercelModel({ model: ${model.constructorExpr} });`);
  lines.push('const memory = createLibsqlMemory({ url: process.env.MEMORY_DB_URL ?? "file:.wappy/memory.db" });');
  lines.push('const sessionProfileStore = createLibsqlSessionProfileStore({ url: process.env.SESSION_PROFILE_DB_URL ?? "file:.wappy/session-profile.db" });');
  lines.push("const router = createLlmRouter({ model });");
  lines.push("const tracer = createInMemoryTracer();");
  lines.push("");

  // Retrieved knowledge/RAG — unconditional (independent of the productivity agent): the local
  // backend (BM25-by-default, already shipped in @wappy_ai/harness) costs nothing extra, so there's
  // no reason to gate it behind anything. `memory.backend` only picks which Knowledge implementation
  // backs it.
  if (memoryBackend === "cognee") {
    lines.push("// Bring-your-own Cognee instance (self-hosted or cloud) — see COGNEE_SETUP.md.");
    lines.push('const knowledge = createCogneeKnowledge({ baseUrl: process.env.COGNEE_BASE_URL!, apiKey: process.env.COGNEE_API_KEY });');
  } else {
    lines.push('const knowledgeClient = createClient({ url: process.env.KNOWLEDGE_DB_URL ?? "file:.wappy/knowledge.db" });');
    lines.push("const knowledge = createKnowledge({ client: knowledgeClient });");
  }
  lines.push("const retrieveRag = createKnowledgeRag({ knowledge, memory });");
  lines.push("");

  // Exported (not just used locally): `wappy dev` (T9.7) needs channel.receive() to turn a raw
  // webhook into InboundMessages before it can call agent.handle() on each one — the Agent itself
  // only exposes handle(), not receive(), since receiving isn't an agent concern. No WhatsApp
  // Message Template is ever configured here — every reply this project sends (the reactive agent's
  // own, or a matched task's, below) is a direct response to an inbound message, so it's always
  // inside the 24h session window Meta opens when the contact messages you; that rule only bites a
  // message that pushes on its own, unprompted, which this project deliberately never does.
  lines.push("export const channel = createWhatsAppChannel({");
  lines.push("  phoneNumberId: process.env.WHATSAPP_PHONE_NUMBER_ID!,");
  lines.push("  accessToken: process.env.WHATSAPP_ACCESS_TOKEN!,");
  lines.push("  clock: systemClock,");
  lines.push("});");
  lines.push("");

  lines.push("// This scaffold ships with no tools wired in. To give the agent tools (a store, a");
  lines.push("// calendar, anything else), see @wappy_ai/core's Tool/ToolProvider interfaces and");
  lines.push("// @wappy_ai/harness's docs on wiring a tool invoker into createAgent below.");
  lines.push(`export const ${productivity ? "reactiveAgent" : "agent"} = createAgent({`);
  lines.push("  channel, memory, router, model, tracer,");
  lines.push("  clock: systemClock,");
  lines.push("  sessionProfileStore,");
  lines.push("  retrieveRag,");
  lines.push("});");
  lines.push("");

  if (productivity) {
    lines.push("// Productivity agent: reads (never writes) the user's own Gmail/Calendar, for ANY question");
    lines.push("// phrased in normal language — no saved tasks, no fixed list of things it can answer. See");
    lines.push('// GOOGLE_SETUP.md for the one-time Google connection; without it, a matched question just');
    lines.push('// replies honestly that it needs "Connect Google" tapped first on the local connect page.');
    lines.push("const googleConfig = {");
    lines.push('  clientId: process.env.GOOGLE_CLIENT_ID ?? "",');
    lines.push('  clientSecret: process.env.GOOGLE_CLIENT_SECRET ?? "",');
    lines.push('  redirectUri: process.env.GOOGLE_REDIRECT_URI ?? "http://localhost:3001/google/callback",');
    lines.push("};");
    lines.push('const googleTokenStore = createGoogleTokenStore({ url: process.env.GOOGLE_TOKENS_DB_URL ?? "file:.wappy/google-tokens.db" });');
    lines.push("const googlePlugin = createGoogleOAuthPlugin({ config: googleConfig, tokenStore: googleTokenStore, clock: systemClock });");
    lines.push("");
    lines.push("const googleAssistant = createGoogleAssistant({");
    lines.push("  model, clock: systemClock,");
    lines.push("  connectors: {");
    lines.push("    gmail: createGmailSearchFn({ config: googleConfig, tokenStore: googleTokenStore, clock: systemClock }),");
    lines.push("    calendar: createCalendarSearchFn({ config: googleConfig, tokenStore: googleTokenStore, clock: systemClock }),");
    lines.push("  },");
    lines.push("});");
    lines.push("");
    lines.push("// Wraps the reactive agent: every inbound message is offered real Gmail/Calendar search tools");
    lines.push("// first (the model itself decides whether the message actually needs them, and constructs its");
    lines.push("// own query/date-range — @wappy_ai/harness's createVercelModel already runs the full");
    lines.push("// multi-step tool-calling loop internally); anything that didn't touch either tool falls");
    lines.push("// through to the normal reactive agent unchanged.");
    lines.push("export const agent = {");
    lines.push("  async handle(message: Parameters<typeof reactiveAgent.handle>[0]) {");
    lines.push("    const routed = await googleAssistant.maybeHandle(message);");
    lines.push("    if (routed.handled) return channel.send(message.contactId, { text: routed.reply! });");
    lines.push("    return reactiveAgent.handle(message);");
    lines.push("  },");
    lines.push("};");
    lines.push("");
    lines.push("export const taskUiServer = createConnectUiServer({ oauthConnect: googlePlugin });");
    lines.push("");
  }

  return lines.join("\n");
}

